window.fixmateTranslate = function (value, locale = 'en') {
  if (!value || locale === 'en') return value;
  const messages = window.FIXMATE_LOCALES[locale]?.messages || {};
  if (messages[value]) return messages[value];
  let translated = value;
  // Dynamic portions (names, counts, dates) are kept intact around localized copy.
  translated = translated.replace(/^Welcome back, (.+)\.$/, 'वापस स्वागत है, $1।');
  translated = translated.replace(/^(\d+) years$/, '$1 वर्ष');
  translated = translated.replace(/^(\d+) years of experience$/, '$1 वर्षों का अनुभव');
  translated = translated.replace(/^(\d+) eligible nearby workers?$/, '$1 पात्र नज़दीकी कामगार');
  translated = translated.replace(/^Found (\d+) eligible workers? nearby · assigned (.+) \((.+) km\)$/, 'पास में $1 पात्र कामगार मिले · $2 ($3 किमी) को चुना गया');
  translated = translated.replace(/^Booking (.+)\.$/, 'बुकिंग $1।');
  translated = translated.replace(/^Welcome, (.+)\.$/, 'स्वागत है, $1।');
  translated = translated.replace(/^(.+) years · (.+)$/, '$1 वर्ष · $2');
  translated = translated.replace(/(\d+) years ·/g, '$1 वर्ष ·');
  translated = translated.replace(/^(.+) km away$/, '$1 किमी दूर');
  translated = translated.replace(/^(.+) yrs$/, '$1 वर्ष');
  translated = translated.replace(/^(.+) · cooperative support record$/, '$1 · सहकारी सहायता रिकॉर्ड');
  translated = translated.replace(/^(.+) worker profiles are on file$/, 'रिकॉर्ड में $1 कामगार प्रोफ़ाइल हैं');
  translated = translated.replace(/^(.+) workers? are on file$/, 'रिकॉर्ड में $1 कामगार हैं');
  translated = translated.replace(/^(.+) · (.+) needs (\d+) more workers?$/, '$1 · $2 में $3 और कामगार चाहिए');
  translated = translated.replace(/^Peak forecast: (.+) · eligible roster: (.+) · (.+)$/, 'अनुमानित अधिकतम मांग: $1 · पात्र सूची: $2 · $3');
  translated = translated.replace(/^(.+) predicted jobs$/, '$1 अनुमानित काम');
  translated = translated.replace(/^(.+) bookings to date$/, 'अब तक $1 बुकिंग');
  translated = translated.replace(/^Synthetic forecast prior\. (\d+) matching real bookings are recorded; at least 10 bookings spanning 28 days are needed for history calibration\.$/, 'पूर्वानुमान का सिंथेटिक आधार। $1 मेल खाती वास्तविक बुकिंग दर्ज हैं; इतिहास से समायोजन के लिए 28 दिनों में कम से कम 10 बुकिंग चाहिए।');
  translated = translated.replace(/^Synthetic ML forecast calibrated using (\d+) real, non-cancelled (.+) bookings mapped to (.+) over the last 56 days\.$/, 'सिंथेटिक ML पूर्वानुमान पिछले 56 दिनों की $1 वास्तविक, रद्द न की गई $2 बुकिंग और $3 क्षेत्र के आधार पर समायोजित है।');
  translated = translated.replace(/^Found (\d+) eligible workers? nearby.*$/, 'पास में $1 पात्र कामगार मिले');
  translated = translated.replace(/^Book (.+)$/, 'बुक करें: $1');
  const partialWords = new Set(['Plumbing','Electrical','Carpentry','Painting','Cleaning','Caregiving','Driving','Gardening','Technician','PRIORITY','Requested','Accepted','Completed','Cancelled','Verified','Unassigned','New','All','transparent_fair_match_v1']);
  const phrases = Object.entries(messages)
    .filter(([english]) => ((english.includes(' ') && english.length >= 8) || partialWords.has(english)) && translated.includes(english))
    .sort((a, b) => b[0].length - a[0].length);
  for (const [english, hindi] of phrases) translated = translated.replaceAll(english, hindi);
  translated = translated.replaceAll(' with ', ' के साथ ');
  translated = translated.replace(/\bjobs\/day\b/g, 'काम/दिन');
  return translated;
};

window.fixmateLocalizeTree = function (root = document.body, locale = 'en') {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const parent = node.parentElement;
    if (!parent || ['SCRIPT','STYLE','CODE','TEXTAREA'].includes(parent.tagName)) continue;
    if (node.__fixmateOriginal === undefined) node.__fixmateOriginal = node.nodeValue;
    const source = node.__fixmateOriginal;
    const translated = window.fixmateTranslate(source, locale);
    if (node.nodeValue !== translated) node.nodeValue = translated;
  }
  root.querySelectorAll?.('[placeholder],[title],[aria-label]').forEach((element) => {
    for (const attribute of ['placeholder','title','aria-label']) {
      const value = element.getAttribute(attribute);
      if (value) {
        const originalKey = `__fixmateOriginal_${attribute}`;
        if (element[originalKey] === undefined) element[originalKey] = value;
        element.setAttribute(attribute, window.fixmateTranslate(element[originalKey], locale));
      }
    }
  });
};
